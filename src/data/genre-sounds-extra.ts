/** One note per 16th step from a list of degrees, `null` for a rest. */
const seq = (degs: (number | null)[], len = 0.9, shift?: number): PhraseNote[] =>
  degs.flatMap((d, i) => (d === null ? [] : [[i, len, d, shift] as PhraseNote]))
const layer = (i: number, label: string, value: number) => ({ id: "layer" + i, label, min: 0, max: 1, step: 0.01, value, fmt: pct, apply: (p: GenreSound["patch"], _f: GenreSound["fx"], v: number) => { p.layers[i].level = v } })
const pitchDrop = (value: number) => ({ id: "pitch", label: "Pitch drop", min: 0, max: 36, step: 1, value, fmt: (v: number) => v + " semitones", apply: (p: GenreSound["patch"], _f: GenreSound["fx"], v: number) => { p.pitch = v ? { semis: v, time: p.pitch?.time ?? 0.05 } : undefined } })
const wobble = (value: number) => ({ id: "wobble", label: "Wobble", min: 0, max: 40, step: 1, value, fmt: cents, apply: (p: GenreSound["patch"], _f: GenreSound["fx"], v: number) => { if (p.lfo) p.lfo.depth = v } })

